package speaker

import "math"

// Cosine returns the cosine similarity between two equal-length vectors, in the
// range [-1, 1]. It returns 0 when either vector is empty, the lengths differ,
// or either vector has zero magnitude. Higher values mean more similar voices.
func Cosine(a, b []float32) float64 {
	if len(a) == 0 || len(a) != len(b) {
		return 0
	}
	var dot, normA, normB float64
	for i := range a {
		av := float64(a[i])
		bv := float64(b[i])
		dot += av * bv
		normA += av * av
		normB += bv * bv
	}
	if normA == 0 || normB == 0 {
		return 0
	}
	return dot / (math.Sqrt(normA) * math.Sqrt(normB))
}
